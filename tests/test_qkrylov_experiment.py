import numpy as np
import pytest

pytest.importorskip("qiskit")

from biasblaster.qkrylov_experiment import (
    EffectiveNoiseParameters,
    assemble_krylov_matrices,
    build_tfim_krylov_plan,
    run_tfim_qkrylov_benchmark,
    sample_pm1_expectations,
    zero_state_pauli_moments,
)


def test_zero_state_pauli_moments_are_sparse_and_normalized():
    moments = zero_state_pauli_moments(2)
    assert moments == {"II": 1.0, "IZ": 1.0, "ZI": 1.0, "ZZ": 1.0}


def test_hadamard_estimators_reconstruct_ideal_krylov_matrices():
    plan = build_tfim_krylov_plan(
        n_qubits=2,
        dimension=2,
        time_step=0.2,
        trotter_steps=1,
    )
    # The plan constructor itself validates the QK generalized eigenproblem;
    # use ideal estimator values generated by a zero-noise benchmark to verify
    # scalar-to-matrix assembly in the executable path.
    result = run_tfim_qkrylov_benchmark(
        n_qubits=2,
        dimension=2,
        time_step=0.2,
        trotter_steps=1,
        total_shots=20_000,
        minimum_shots=100,
        seed=3,
        noise=EffectiveNoiseParameters(p1=0, p2=0, p_meas=0, p_init=0),
        calibration_relative_sigma=0.0,
    )
    assert result.observable_first_order_rmse < 1e-12
    assert np.isfinite(result.plan.ideal_qk_energy)
    assert result.plan.estimators
    assert np.isclose(result.policies[0].energy, plan.ideal_qk_energy, atol=1e-10)


def test_default_effective_noise_benchmark_runs_and_allocates_all_shots():
    shots = 30_000
    result = run_tfim_qkrylov_benchmark(
        n_qubits=2,
        dimension=2,
        time_step=0.2,
        trotter_steps=1,
        total_shots=shots,
        minimum_shots=100,
        seed=5,
    )
    assert result.uniform_allocation.sum() == shots
    assert result.adaptive_allocation.sum() == shots
    assert result.observable_first_order_rmse >= 0.0
    assert result.observable_first_order_max_error >= result.observable_first_order_rmse
    assert {policy.name for policy in result.policies} == {
        "ideal_qk",
        "noisy_uniform",
        "noise_regularized",
        "debiased_regularized",
        "adaptive_full",
    }


def test_pm1_sampler_respects_exact_expectation_extremes():
    rng = np.random.default_rng(10)
    sampled = sample_pm1_expectations([1.0, -1.0], [100, 100], rng)
    assert np.allclose(sampled, [1.0, -1.0])
